create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique not null,
  category text not null,
  excerpt text,
  content text not null,
  published boolean not null default false,
  author_id uuid references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.articles enable row level security;
create policy "Public can read published articles" on public.articles
for select using (published = true);
create policy "Authenticated editors can insert articles" on public.articles
for insert to authenticated with check (auth.uid() = author_id);
create policy "Authors can update their articles" on public.articles
for update to authenticated using (auth.uid() = author_id) with check (auth.uid() = author_id);
create policy "Authors can delete their articles" on public.articles
for delete to authenticated using (auth.uid() = author_id);
